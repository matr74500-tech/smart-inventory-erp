-- إضافة/تعديل مندوب
CREATE OR REPLACE FUNCTION public.save_sales_representative(
  _id uuid DEFAULT NULL,
  _name text,
  _phone text,
  _commission_rate numeric,
  _active boolean
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE rep_id uuid;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','sales_reps')
     OR NOT public.employee_can(auth.uid(),'actions','sales_reps.manage') THEN
    RAISE EXCEPTION 'غير مصرح بإدارة المناديب';
  END IF;
  IF _commission_rate IS NULL OR _commission_rate < 0 OR _commission_rate > 100 THEN
    RAISE EXCEPTION 'نسبة العمولة غير صالحة';
  END IF;
  IF _id IS NOT NULL THEN
    UPDATE public.sales_representatives
      SET name=_name, phone=_phone, commission_rate=_commission_rate,
          active=_active, updated_at=now()
    WHERE id=_id RETURNING id INTO rep_id;
    IF rep_id IS NULL THEN RAISE EXCEPTION 'المندوب غير موجود'; END IF;
  ELSE
    INSERT INTO public.sales_representatives (name,phone,commission_rate,active,created_by)
      VALUES (_name,_phone,_commission_rate,_active,auth.uid())
      RETURNING id INTO rep_id;
  END IF;
  RETURN rep_id;
END $$;

-- حساب وخلق عمولة لمندوب على فاتورة
CREATE OR REPLACE FUNCTION public.calculate_rep_commission(
  _rep_id uuid,
  _sale_invoice_id uuid
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  rep_record public.sales_representatives;
  inv_record public.sales_invoices;
  comm_amount numeric;
  period date;
  comm_id uuid;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','sales_reps')
     OR NOT public.employee_can(auth.uid(),'actions','sales_reps.manage') THEN
    RAISE EXCEPTION 'غير مصرح بحساب العمولات';
  END IF;
  SELECT * INTO rep_record FROM public.sales_representatives WHERE id=_rep_id AND active;
  IF NOT FOUND THEN RAISE EXCEPTION 'المندوب غير موجود أو غير نشط'; END IF;
  SELECT * INTO inv_record FROM public.sales_invoices WHERE id=_sale_invoice_id AND status='posted';
  IF NOT FOUND THEN RAISE EXCEPTION 'الفاتورة غير موجودة أو غيرمرحّلة'; END IF;

  comm_amount := (inv_record.total_yer * rep_record.commission_rate / 100);
  period := date_trunc('month', inv_record.posted_at)::date;

  INSERT INTO public.rep_commissions (rep_id, sale_invoice_id, commission_amount, period_month, created_by)
    VALUES (_rep_id, _sale_invoice_id, comm_amount, period, auth.uid())
    RETURNING id INTO comm_id;
  RETURN comm_id;
END $$;

-- دفع عمولة لمندوب
CREATE OR REPLACE FUNCTION public.pay_rep_commission(
  _commission_id uuid,
  _payment_method text
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  comm_record public.rep_commissions;
  rep_record public.sales_representatives;
  tx_id uuid;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','sales_reps')
     OR NOT public.employee_can(auth.uid(),'actions','sales_reps.manage') THEN
    RAISE EXCEPTION 'غير مصرح بدفع العمولات';
  END IF;
  SELECT * INTO comm_record FROM public.rep_commissions WHERE id=_commission_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'سجل العمولة غير موجود'; END IF;
  IF comm_record.paid THEN RAISE EXCEPTION 'العمولة مدفوعة بالفعل'; END IF;

  SELECT * INTO rep_record FROM public.sales_representatives WHERE id=comm_record.rep_id;

  UPDATE public.rep_commissions SET paid=true, paid_at=now(), paid_by=auth.uid()
    WHERE id=_commission_id;

  -- إنشاء حركة صندوق بالصرف
  INSERT INTO public.cash_transactions (
    source_type, source_id, currency_code, amount, rate_to_yer,
    payment_method, affects_drawer, created_by
  ) VALUES (
    'rep_commission', _commission_id, 'YER', -(comm_record.commission_amount), 1,
    coalesce(nullif(btrim(_payment_method),''),'نقدي'), true, auth.uid()
  ) RETURNING id INTO tx_id;
END $$;

