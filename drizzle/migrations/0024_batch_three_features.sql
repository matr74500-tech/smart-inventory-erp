-- تسجيل مصروف وإنشاء حركة صندوق مقابلة
CREATE OR REPLACE FUNCTION public.record_general_expense(
  _expense_type text,
  _category text,
  _description text,
  _amount numeric,
  _currency_code text,
  _rate_to_yer numeric,
  _expense_date date,
  _payment_method text
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  expense_id uuid;
  tx_id uuid;
  v_affects boolean := true;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','expenses')
     OR NOT public.employee_can(auth.uid(),'actions','expenses.manage') THEN
    RAISE EXCEPTION 'غير مصرح بتسجيل المصروفات';
  END IF;
  IF _amount IS NULL OR _amount <= 0 THEN
    RAISE EXCEPTION 'المبلغ غير صالح';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.currencies WHERE code=_currency_code AND active) THEN
    RAISE EXCEPTION 'العملة غير موجودة أو غير نشطة';
  END IF;
  IF _expense_type NOT IN ('daily','monthly','recurring','operational') THEN
    RAISE EXCEPTION 'نوع مصروف غير صالح';
  END IF;

  INSERT INTO public.general_expenses (
    expense_type, category, description, amount, currency_code,
    rate_to_yer, expense_date, created_by
  ) VALUES (
    _expense_type, _category, _description, _amount, _currency_code,
    _rate_to_yer, _expense_date, auth.uid()
  ) RETURNING id INTO expense_id;

  -- إنشاء حركة صندوق سالبة (صرف من الدرج)
  INSERT INTO public.cash_transactions (
    source_type, source_id, currency_code, amount, rate_to_yer,
    payment_method, affects_drawer, created_by
  ) VALUES (
    'expense', expense_id, _currency_code, -(_amount / _rate_to_yer), _rate_to_yer,
    coalesce(nullif(btrim(_payment_method),''),'نقدي'), true, auth.uid()
  ) RETURNING id INTO tx_id;

  UPDATE public.general_expenses SET cash_transaction_id = tx_id WHERE id = expense_id;

  RETURN expense_id;
END $$;

CREATE OR REPLACE FUNCTION public.record_general_expense_offline(
  _operation_id uuid,
  _expense_type text,
  _category text,
  _description text,
  _amount numeric,
  _currency_code text,
  _rate_to_yer numeric,
  _expense_date date,
  _payment_method text
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.offline_operation_receipts WHERE operation_id = _operation_id) THEN
    RETURN (SELECT id FROM public.general_expenses WHERE id IN (
      SELECT (details->>'expense_id')::uuid FROM public.system_activity_log
      WHERE action = 'record_expense' AND details->>'operation_id' = _operation_id
      LIMIT 1
    ));
  END IF;
  INSERT INTO public.offline_operation_receipts (operation_id, operation_kind, user_id)
    VALUES (_operation_id, 'record_expense', auth.uid());
  RETURN public.record_general_expense(
    _expense_type, _category, _description, _amount, _currency_code,
    _rate_to_yer, _expense_date, _payment_method
  );
END $$;

REVOKE ALL ON FUNCTION public.record_general_expense(text,text,text,numeric,text,numeric,date,text) FROM PUBLIC,anon;
