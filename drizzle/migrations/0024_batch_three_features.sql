-- تحديد سعر حر لصنف مع توثيق الفرق عن السعر الافتراضي (للمدير فقط)
CREATE OR REPLACE FUNCTION public.set_product_free_price(
  _product_id uuid,
  _price_category_id uuid,
  _free_price numeric
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  default_price numeric;
  diff numeric;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','sales')
     OR NOT public.employee_can(auth.uid(),'actions','sales.override_price') THEN
    RAISE EXCEPTION 'غير مصرح بتحديد السعر الحر؛ هذه صلاحية المدير فقط';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.products WHERE id=_product_id) THEN
    RAISE EXCEPTION 'الصنف غير موجود';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.price_categories WHERE id=_price_category_id AND active) THEN
    RAISE EXCEPTION 'فئة السعر غير موجودة أو غير نشطة';
  END IF;
  IF _free_price IS NULL OR _free_price < 0 THEN
    RAISE EXCEPTION 'السعر غير صالح';
  END IF;

  SELECT price INTO default_price FROM public.products WHERE id=_product_id;
  diff := _free_price - coalesce(default_price,0);

  INSERT INTO public.product_free_prices (product_id, price_category_id, free_price, default_price, price_difference, updated_by)
    VALUES (_product_id, _price_category_id, _free_price, coalesce(default_price,0), diff, auth.uid())
    ON CONFLICT (product_id, price_category_id) DO UPDATE
      SET free_price=excluded.free_price, default_price=excluded.default_price,
          price_difference=excluded.price_difference, updated_by=excluded.updated_by,
          updated_at=now();
END $$;

REVOKE ALL ON FUNCTION public.set_product_free_price(uuid,uuid,numeric) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.set_product_free_price(uuid,uuid,numeric) TO authenticated;

