CREATE OR REPLACE FUNCTION public.save_supplier(
  _id uuid, _name text, _phone text, _address text, _notes text
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE supplier_id uuid;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','suppliers')
    OR NOT public.employee_can(auth.uid(),'actions','suppliers.manage') THEN
    RAISE EXCEPTION 'غير مصرح بإدارة الموردين';
  END IF;
  IF nullif(btrim(_name),'') IS NULL THEN RAISE EXCEPTION 'اسم المورد مطلوب'; END IF;
  IF _id IS NULL THEN
    INSERT INTO public.suppliers (name,phone,address,notes)
    VALUES (btrim(_name),btrim(coalesce(_phone,'')),btrim(coalesce(_address,'')),nullif(btrim(_notes),''))
    RETURNING id INTO supplier_id;
  ELSE
    UPDATE public.suppliers SET name=btrim(_name),phone=btrim(coalesce(_phone,'')),
      address=btrim(coalesce(_address,'')),notes=nullif(btrim(_notes),''),updated_at=now()
      WHERE id=_id AND active RETURNING id INTO supplier_id;
    IF supplier_id IS NULL THEN RAISE EXCEPTION 'المورد غير موجود أو غير نشط'; END IF;
  END IF;
  RETURN supplier_id;
END $$;

CREATE OR REPLACE FUNCTION public.save_product_supplier(
  _product_id uuid, _supplier_id uuid, _supplier_sku text, _last_cost numeric, _is_primary boolean
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','suppliers')
    OR NOT public.employee_can(auth.uid(),'actions','suppliers.manage') THEN
    RAISE EXCEPTION 'غير مصرح بربط المورد بالصنف';
  END IF;
  IF _last_cost IS NULL OR _last_cost < 0
    OR NOT EXISTS (SELECT 1 FROM public.products WHERE id=_product_id)
    OR NOT EXISTS (SELECT 1 FROM public.suppliers WHERE id=_supplier_id AND active) THEN
    RAISE EXCEPTION 'بيانات ربط المورد غير صالحة';
  END IF;
  IF coalesce(_is_primary,false) THEN
    UPDATE public.product_suppliers SET is_primary=false,updated_at=now()
      WHERE product_id=_product_id AND is_primary;
  END IF;
  INSERT INTO public.product_suppliers (product_id,supplier_id,supplier_sku,last_cost,is_primary)
  VALUES (_product_id,_supplier_id,nullif(btrim(_supplier_sku),''),_last_cost,coalesce(_is_primary,false))
  ON CONFLICT (product_id,supplier_id) DO UPDATE SET supplier_sku=excluded.supplier_sku,
    last_cost=excluded.last_cost,is_primary=excluded.is_primary,updated_at=now();
END $$;

CREATE OR REPLACE FUNCTION public.archive_supplier(_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','suppliers')
    OR NOT public.employee_can(auth.uid(),'actions','suppliers.manage') THEN
    RAISE EXCEPTION 'غير مصرح بإيقاف المورد';
  END IF;
  UPDATE public.suppliers SET active=false,updated_at=now() WHERE id=_id AND active;
  IF NOT FOUND THEN RAISE EXCEPTION 'المورد غير موجود'; END IF;
END $$;

CREATE OR REPLACE FUNCTION public.set_initial_stocks(_product uuid, _balances jsonb)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE item jsonb; warehouse_id uuid; quantity numeric;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','inventory')
    OR NOT public.employee_can(auth.uid(),'actions','inventory.create')
    OR NOT public.employee_can(auth.uid(),'actions','stocktake.adjust')
    OR NOT public.employee_can(auth.uid(),'fields','quantity') THEN
    RAISE EXCEPTION 'غير مصرح بإدخال أرصدة افتتاحية';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.products WHERE id=_product)
    OR jsonb_typeof(_balances) <> 'array' THEN
    RAISE EXCEPTION 'بيانات الأرصدة الافتتاحية غير صالحة';
  END IF;
  FOR item IN SELECT value FROM jsonb_array_elements(_balances) LOOP
    warehouse_id := (item->>'warehouse_id')::uuid;
    quantity := (item->>'quantity')::numeric;
    IF warehouse_id IS NULL OR quantity IS NULL OR quantity < 0
      OR NOT EXISTS (SELECT 1 FROM public.warehouses WHERE id=warehouse_id) THEN
      RAISE EXCEPTION 'المستودع أو الكمية غير صالح';
    END IF;
    IF quantity > 0 THEN
      PERFORM public.set_stock(_product,warehouse_id,quantity,'رصيد افتتاحي');
    END IF;
  END LOOP;
END $$;

