CREATE OR REPLACE FUNCTION public.save_purchase_order_draft(
  _id uuid, _supplier_id uuid, _warehouse uuid, _notes text, _items jsonb
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE order_id uuid; order_status text; item jsonb; product_id uuid; quantity numeric; unit_cost numeric;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','purchase_orders')
    OR NOT public.employee_can(auth.uid(),'actions','purchase_orders.manage') THEN
    RAISE EXCEPTION 'غير مصرح بإدارة أوامر الشراء';
  END IF;
  IF _supplier_id IS NULL OR _warehouse IS NULL OR jsonb_typeof(_items) <> 'array' OR jsonb_array_length(_items)=0
    OR NOT EXISTS (SELECT 1 FROM public.suppliers WHERE id=_supplier_id AND active)
    OR NOT EXISTS (SELECT 1 FROM public.warehouses WHERE id=_warehouse) THEN
    RAISE EXCEPTION 'بيانات أمر الشراء غير صالحة';
  END IF;
  IF _id IS NULL THEN
    INSERT INTO public.purchase_orders (supplier_id,warehouse_id,notes,created_by)
    VALUES (_supplier_id,_warehouse,_notes,auth.uid()) RETURNING id INTO order_id;
  ELSE
    SELECT status INTO order_status FROM public.purchase_orders
      WHERE id=_id AND created_by=auth.uid() FOR UPDATE;
    IF order_status IS DISTINCT FROM 'draft' THEN RAISE EXCEPTION 'لا يمكن تعديل أمر غير مسودة'; END IF;
    order_id := _id;
    UPDATE public.purchase_orders SET supplier_id=_supplier_id,warehouse_id=_warehouse,notes=_notes WHERE id=order_id;
    DELETE FROM public.purchase_order_items WHERE purchase_order_items.order_id=order_id;
  END IF;
  FOR item IN SELECT value FROM jsonb_array_elements(_items) LOOP
    product_id := (item->>'product_id')::uuid;
    quantity := (item->>'quantity')::numeric;
    unit_cost := (item->>'unit_cost')::numeric;
    IF quantity IS NULL OR quantity <= 0 OR unit_cost IS NULL OR unit_cost < 0
      OR NOT EXISTS (SELECT 1 FROM public.products WHERE id=product_id) THEN
      RAISE EXCEPTION 'صنف أو كمية أو تكلفة غير صالحة';
    END IF;
    INSERT INTO public.purchase_order_items (order_id,product_id,quantity,unit_cost)
      VALUES (order_id,product_id,quantity,unit_cost);
  END LOOP;
  RETURN order_id;
END $$;

CREATE OR REPLACE FUNCTION public.submit_purchase_order(_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','purchase_orders')
    OR NOT public.employee_can(auth.uid(),'actions','purchase_orders.manage') THEN
    RAISE EXCEPTION 'غير مصرح بإرسال أمر الشراء';
  END IF;
  UPDATE public.purchase_orders SET status='ordered',submitted_at=now()
    WHERE id=_id AND status='draft' AND created_by=auth.uid();
  IF NOT FOUND THEN RAISE EXCEPTION 'الأمر غير موجود أو ليس مسودة أنشأها المستخدم'; END IF;
END $$;

CREATE OR REPLACE FUNCTION public.receive_purchase_order(_id uuid)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE po public.purchase_orders; supplier_name text; items jsonb; invoice_id uuid;
BEGIN
  IF NOT public.employee_can(auth.uid(),'pages','purchase_orders')
    OR NOT public.employee_can(auth.uid(),'actions','purchase_orders.manage')
    OR NOT public.employee_can(auth.uid(),'pages','purchases')
    OR NOT public.employee_can(auth.uid(),'actions','purchases.post')
    OR NOT public.employee_can(auth.uid(),'fields','quantity')
    OR NOT public.employee_can(auth.uid(),'fields','cost')
    OR NOT public.employee_can(auth.uid(),'fields','supplier') THEN
    RAISE EXCEPTION 'غير مصرح باستلام أمر الشراء';
  END IF;
  SELECT * INTO po FROM public.purchase_orders WHERE id=_id FOR UPDATE;
  IF po.id IS NULL OR po.status <> 'ordered' THEN RAISE EXCEPTION 'الأمر غير موجود أو لم يُرسل'; END IF;
  SELECT name INTO supplier_name FROM public.suppliers WHERE id=po.supplier_id AND active;
  SELECT jsonb_agg(jsonb_build_object('product_id',product_id,'qty',quantity,'cost',unit_cost))
    INTO items FROM public.purchase_order_items WHERE order_id=po.id;
  IF items IS NULL THEN RAISE EXCEPTION 'أمر الشراء فارغ'; END IF;
  invoice_id := public.post_purchase(supplier_name,po.warehouse_id,items);
  UPDATE public.purchase_orders SET status='received',received_at=now(),purchase_invoice_id=invoice_id WHERE id=po.id;
  RETURN invoice_id;
END $$;

