CREATE OR REPLACE FUNCTION public.save_sale_draft(
  _id uuid, _customer_id uuid, _customer_name text, _warehouse uuid,
  _currency_code text, _rate_to_yer numeric, _payment_method text,
  _affects_drawer boolean, _paid_amount numeric, _discount_yer numeric,
  _tax_yer numeric, _notes text, _items jsonb
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE invoice_id uuid; item jsonb; subtotal numeric := 0; invoice_status text;
  current_rate numeric; quantity numeric; price numeric; product_id uuid; tier text;
BEGIN
  IF NOT public.employee_can(auth.uid(), 'pages', 'sales')
    OR NOT public.employee_can(auth.uid(), 'actions', 'sales.draft') THEN
    RAISE EXCEPTION 'غير مصرح بحفظ فواتير البيع';
  END IF;
  IF _warehouse IS NULL OR _rate_to_yer IS NULL OR _rate_to_yer <= 0
    OR _paid_amount IS NULL OR _paid_amount < 0
    OR coalesce(_discount_yer,0) < 0 OR coalesce(_tax_yer,0) < 0
    OR jsonb_typeof(_items) <> 'array' OR jsonb_array_length(_items)=0 THEN
    RAISE EXCEPTION 'بيانات الفاتورة غير صالحة';
  END IF;
  SELECT rate_to_yer INTO current_rate FROM public.exchange_rates
    WHERE currency_code=_currency_code ORDER BY effective_at DESC, created_at DESC LIMIT 1;
  IF current_rate IS NULL OR current_rate <> _rate_to_yer THEN
    RAISE EXCEPTION 'تغير سعر الصرف؛ حدّث الفاتورة بالسعر الحالي';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.warehouses WHERE id=_warehouse) THEN RAISE EXCEPTION 'المستودع غير موجود'; END IF;
  IF _customer_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.customers WHERE id=_customer_id AND active) THEN
    RAISE EXCEPTION 'العميل غير موجود أو غير نشط';
  END IF;
  IF _id IS NULL THEN
    INSERT INTO public.sales_invoices (customer_id, customer_name, warehouse_id, currency_code, exchange_rate_to_yer,
      payment_method, affects_drawer, paid_amount, discount_yer, tax_yer, notes, created_by)
    VALUES (_customer_id, nullif(btrim(_customer_name),''), _warehouse, _currency_code, _rate_to_yer,
      coalesce(_payment_method,'نقدي'), coalesce(_affects_drawer,true), _paid_amount,
      coalesce(_discount_yer,0), coalesce(_tax_yer,0), _notes, auth.uid())
    RETURNING id INTO invoice_id;
  ELSE
    SELECT status INTO invoice_status FROM public.sales_invoices WHERE id=_id AND created_by=auth.uid() FOR UPDATE;
    IF invoice_status IS DISTINCT FROM 'draft' THEN RAISE EXCEPTION 'لا يمكن تعديل فاتورة غير مسودة'; END IF;
    invoice_id := _id;
    UPDATE public.sales_invoices SET customer_id=_customer_id, customer_name=nullif(btrim(_customer_name),''),
      warehouse_id=_warehouse, currency_code=_currency_code, exchange_rate_to_yer=_rate_to_yer,
      payment_method=coalesce(_payment_method,'نقدي'), affects_drawer=coalesce(_affects_drawer,true),
      paid_amount=_paid_amount, discount_yer=coalesce(_discount_yer,0), tax_yer=coalesce(_tax_yer,0),
      notes=_notes WHERE id=invoice_id;
    DELETE FROM public.sales_items WHERE sales_items.invoice_id=invoice_id;
  END IF;
  FOR item IN SELECT value FROM jsonb_array_elements(_items) LOOP
    product_id := (item->>'product_id')::uuid;
    quantity := (item->>'quantity')::numeric;
    price := (item->>'unit_price_yer')::numeric;
    tier := coalesce(item->>'price_tier','price');
    IF quantity IS NULL OR quantity <= 0 OR price IS NULL OR price < 0
      OR tier NOT IN ('price','price_special','price_half','price_wholesale','price_bulk') THEN
      RAISE EXCEPTION 'بيانات صنف غير صالحة';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.products WHERE id=product_id) THEN RAISE EXCEPTION 'الصنف غير موجود'; END IF;
    IF NOT public.employee_can(auth.uid(), 'actions', 'sales.override_price') AND NOT EXISTS (
      SELECT 1 FROM public.products p WHERE p.id=product_id AND
        CASE tier
          WHEN 'price' THEN p.price
          WHEN 'price_special' THEN p.price_special
          WHEN 'price_half' THEN p.price_half
          WHEN 'price_wholesale' THEN p.price_wholesale
          ELSE p.price_bulk
        END = price
    ) THEN RAISE EXCEPTION 'لا تملك صلاحية تعديل سعر الصنف'; END IF;
    INSERT INTO public.sales_items (invoice_id, product_id, quantity, unit_price_yer, price_tier, total_yer)
      VALUES (invoice_id, product_id, quantity, price, tier, quantity*price);
    subtotal := subtotal + quantity*price;
  END LOOP;
  IF _paid_amount * _rate_to_yer > greatest(0, subtotal-coalesce(_discount_yer,0)+coalesce(_tax_yer,0)) THEN
    RAISE EXCEPTION 'المبلغ المدفوع أكبر من إجمالي الفاتورة';
  END IF;
  UPDATE public.sales_invoices SET subtotal_yer=subtotal,
    total_yer=greatest(0, subtotal-discount_yer+tax_yer) WHERE id=invoice_id;
  RETURN invoice_id;
END $$;

CREATE OR REPLACE FUNCTION public.post_sale(_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE inv public.sales_invoices; line record; available numeric; due_yer numeric;
BEGIN
  IF NOT public.employee_can(auth.uid(), 'pages', 'sales')
    OR NOT public.employee_can(auth.uid(), 'actions', 'sales.post')
    OR NOT public.employee_can(auth.uid(), 'fields', 'quantity') THEN
    RAISE EXCEPTION 'غير مصرح بترحيل فاتورة البيع';
  END IF;
  SELECT * INTO inv FROM public.sales_invoices WHERE id=_id FOR UPDATE;
  IF inv.id IS NULL OR inv.status <> 'draft' THEN RAISE EXCEPTION 'الفاتورة غير موجودة أو ليست مسودة'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.sales_items WHERE invoice_id=inv.id) THEN RAISE EXCEPTION 'الفاتورة فارغة'; END IF;
  IF inv.affects_drawer AND EXISTS (
    SELECT 1 FROM public.daily_cash_closings WHERE business_date=current_date AND currency_code=inv.currency_code
  ) THEN RAISE EXCEPTION 'تم إقفال الصندوق لهذه العملة اليوم'; END IF;
  FOR line IN
    SELECT product_id, sum(quantity) AS quantity
    FROM public.sales_items WHERE invoice_id=inv.id GROUP BY product_id ORDER BY product_id
  LOOP
    SELECT quantity INTO available FROM public.stock
      WHERE product_id=line.product_id AND warehouse_id=inv.warehouse_id FOR UPDATE;
    IF coalesce(available,0) < line.quantity THEN RAISE EXCEPTION 'الرصيد غير كافٍ للصنف %', line.product_id; END IF;
    UPDATE public.stock SET quantity=quantity-line.quantity, updated_at=now()
      WHERE product_id=line.product_id AND warehouse_id=inv.warehouse_id;
    INSERT INTO public.stock_movements (product_id, warehouse_id, kind, quantity, user_id, note)
      VALUES (line.product_id, inv.warehouse_id, 'sale', -line.quantity, auth.uid(), 'فاتورة بيع '||inv.number);
  END LOOP;
  due_yer := greatest(0, inv.total_yer - inv.paid_amount*inv.exchange_rate_to_yer);
  IF inv.customer_id IS NOT NULL THEN
    UPDATE public.customers SET balance_yer=balance_yer+due_yer, last_sale_at=now(), updated_at=now()
      WHERE id=inv.customer_id;
  END IF;
  IF inv.paid_amount > 0 AND inv.affects_drawer THEN
    INSERT INTO public.cash_transactions (source_type, source_id, currency_code, amount, rate_to_yer,
      payment_method, affects_drawer, created_by)
    VALUES ('sale', inv.id, inv.currency_code, inv.paid_amount, inv.exchange_rate_to_yer,
      inv.payment_method, true, auth.uid());
  END IF;
  UPDATE public.sales_invoices SET status='posted', posted_at=now() WHERE id=inv.id;
END $$;

CREATE OR REPLACE FUNCTION public.save_voucher_draft(
  _id uuid, _kind text, _customer_id uuid, _payee text, _category text,
  _amount numeric, _currency_code text, _rate_to_yer numeric, _payment_method text,
  _affects_drawer boolean, _notes text
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE voucher_id uuid; voucher_status text; current_rate numeric;
BEGIN
  IF NOT public.employee_can(auth.uid(), 'pages', 'cash')
    OR NOT public.employee_can(auth.uid(), 'actions', 'cash.manage') THEN
    RAISE EXCEPTION 'غير مصرح بإدارة السندات';
  END IF;
  IF _kind NOT IN ('receipt','payment') OR _amount IS NULL OR _amount <= 0 OR _rate_to_yer IS NULL OR _rate_to_yer <= 0 THEN
    RAISE EXCEPTION 'بيانات السند غير صالحة';
  END IF;
  SELECT rate_to_yer INTO current_rate FROM public.exchange_rates
    WHERE currency_code=_currency_code ORDER BY effective_at DESC, created_at DESC LIMIT 1;
  IF current_rate IS NULL OR current_rate <> _rate_to_yer THEN RAISE EXCEPTION 'سعر الصرف غير محدث'; END IF;
  IF _customer_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.customers WHERE id=_customer_id AND active) THEN
    RAISE EXCEPTION 'العميل غير موجود أو غير نشط';
  END IF;
  IF _id IS NULL THEN
    INSERT INTO public.vouchers (kind, customer_id, payee, category, amount, currency_code, exchange_rate_to_yer,
      payment_method, affects_drawer, notes, created_by)
    VALUES (_kind, _customer_id, nullif(btrim(_payee),''), coalesce(nullif(btrim(_category),''),'عام'),
      _amount, _currency_code, _rate_to_yer, coalesce(_payment_method,'نقدي'), coalesce(_affects_drawer,true), _notes, auth.uid())
    RETURNING id INTO voucher_id;
  ELSE
    SELECT status INTO voucher_status FROM public.vouchers WHERE id=_id AND created_by=auth.uid() FOR UPDATE;
    IF voucher_status IS DISTINCT FROM 'draft' THEN RAISE EXCEPTION 'لا يمكن تعديل سند غير مسودة'; END IF;
    UPDATE public.vouchers SET kind=_kind, customer_id=_customer_id, payee=nullif(btrim(_payee),''),
      category=coalesce(nullif(btrim(_category),''),'عام'), amount=_amount, currency_code=_currency_code,
      exchange_rate_to_yer=_rate_to_yer, payment_method=coalesce(_payment_method,'نقدي'),
      affects_drawer=coalesce(_affects_drawer,true), notes=_notes WHERE id=_id;
    voucher_id := _id;
  END IF;
  RETURN voucher_id;
END $$;

CREATE OR REPLACE FUNCTION public.post_voucher(_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v public.vouchers;
BEGIN
  IF NOT public.employee_can(auth.uid(), 'pages', 'cash')
    OR NOT public.employee_can(auth.uid(), 'actions', 'cash.manage') THEN
    RAISE EXCEPTION 'غير مصرح بترحيل السند';
  END IF;
  SELECT * INTO v FROM public.vouchers WHERE id=_id FOR UPDATE;
  IF v.id IS NULL OR v.status <> 'draft' THEN RAISE EXCEPTION 'السند غير موجود أو ليس مسودة'; END IF;
  IF v.affects_drawer AND EXISTS (
    SELECT 1 FROM public.daily_cash_closings WHERE business_date=current_date AND currency_code=v.currency_code
  ) THEN RAISE EXCEPTION 'تم إقفال الصندوق لهذه العملة اليوم'; END IF;
  IF v.affects_drawer THEN
    INSERT INTO public.cash_transactions (source_type, source_id, currency_code, amount, rate_to_yer,
      payment_method, affects_drawer, created_by)
    VALUES ('voucher', v.id, v.currency_code, CASE v.kind WHEN 'receipt' THEN v.amount ELSE -v.amount END,
      v.exchange_rate_to_yer, v.payment_method, true, auth.uid());
  END IF;
  IF v.customer_id IS NOT NULL THEN
    UPDATE public.customers SET balance_yer=balance_yer+
      CASE v.kind WHEN 'receipt' THEN -v.amount*v.exchange_rate_to_yer ELSE v.amount*v.exchange_rate_to_yer END,
      updated_at=now()
    WHERE id=v.customer_id;
  END IF;
  UPDATE public.vouchers SET status='posted', posted_at=now() WHERE id=v.id;
END $$;

CREATE OR REPLACE FUNCTION public.close_daily_cash(_business_date date, _counts jsonb, _notes text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE item jsonb; code text; opening numeric; counted numeric; expected numeric;
BEGIN
  IF NOT public.employee_can(auth.uid(), 'pages', 'cash')
    OR NOT public.employee_can(auth.uid(), 'actions', 'cash.close') THEN
    RAISE EXCEPTION 'غير مصرح بإقفال الصندوق';
  END IF;
  IF _business_date IS NULL OR _business_date > current_date OR jsonb_typeof(_counts) <> 'array' OR jsonb_array_length(_counts)=0 THEN
    RAISE EXCEPTION 'بيانات الإقفال غير صالحة';
  END IF;
  FOR item IN SELECT value FROM jsonb_array_elements(_counts) LOOP
    code := item->>'currency_code';
    opening := (item->>'opening_amount')::numeric;
    counted := (item->>'counted_amount')::numeric;
    IF opening IS NULL OR counted IS NULL OR opening < 0 OR counted < 0
      OR NOT EXISTS (SELECT 1 FROM public.currencies WHERE currencies.code=code AND active) THEN
      RAISE EXCEPTION 'أدخل رصيد افتتاح وعدًّا صحيحًا لكل عملة';
    END IF;
    SELECT opening + coalesce(sum(amount),0) INTO expected
      FROM public.cash_transactions
      WHERE affects_drawer AND currency_code=code AND created_at::date=_business_date;
    INSERT INTO public.daily_cash_closings (business_date, currency_code, opening_amount, expected_amount,
      counted_amount, difference, notes, closed_by, closed_at)
    VALUES (_business_date, code, opening, expected, counted, counted-expected, _notes, auth.uid(), now())
    ON CONFLICT (business_date, currency_code) DO UPDATE SET
      opening_amount=excluded.opening_amount, expected_amount=excluded.expected_amount,
      counted_amount=excluded.counted_amount, difference=excluded.difference,
      notes=excluded.notes, closed_by=excluded.closed_by, closed_at=excluded.closed_at;
  END LOOP;
END $$;

