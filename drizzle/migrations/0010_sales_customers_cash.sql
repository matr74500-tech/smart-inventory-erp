CREATE TABLE public.customers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  phone text NOT NULL DEFAULT '',
  secondary_phone text,
  address text NOT NULL DEFAULT '',
  customer_type text NOT NULL DEFAULT 'cash' CHECK (customer_type IN ('cash', 'credit', 'wholesale')),
  credit_limit_yer numeric NOT NULL DEFAULT 0 CHECK (credit_limit_yer >= 0),
  balance_yer numeric NOT NULL DEFAULT 0,
  inactive_alert_enabled boolean NOT NULL DEFAULT true,
  active boolean NOT NULL DEFAULT true,
  last_sale_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX customers_active_name ON public.customers (active, name);

CREATE TABLE public.sales_invoices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'posted', 'cancelled')),
  customer_id uuid REFERENCES public.customers(id) ON DELETE SET NULL,
  customer_name text,
  warehouse_id uuid NOT NULL REFERENCES public.warehouses(id),
  currency_code text NOT NULL REFERENCES public.currencies(code),
  exchange_rate_to_yer numeric NOT NULL CHECK (exchange_rate_to_yer > 0),
  payment_method text NOT NULL DEFAULT 'نقدي',
  affects_drawer boolean NOT NULL DEFAULT true,
  paid_amount numeric NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
  subtotal_yer numeric NOT NULL DEFAULT 0 CHECK (subtotal_yer >= 0),
  discount_yer numeric NOT NULL DEFAULT 0 CHECK (discount_yer >= 0),
  tax_yer numeric NOT NULL DEFAULT 0 CHECK (tax_yer >= 0),
  total_yer numeric NOT NULL DEFAULT 0 CHECK (total_yer >= 0),
  notes text,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  posted_at timestamptz
);

CREATE INDEX sales_invoices_posted_date ON public.sales_invoices (posted_at DESC) WHERE status = 'posted';
CREATE INDEX sales_invoices_customer ON public.sales_invoices (customer_id, posted_at DESC);

CREATE TABLE public.sales_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invoice_id uuid NOT NULL REFERENCES public.sales_invoices(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity numeric NOT NULL CHECK (quantity > 0),
  unit_price_yer numeric NOT NULL CHECK (unit_price_yer >= 0),
  price_tier text NOT NULL DEFAULT 'price',
  total_yer numeric NOT NULL CHECK (total_yer >= 0)
);

CREATE INDEX sales_items_invoice ON public.sales_items (invoice_id);

CREATE TABLE public.vouchers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  kind text NOT NULL CHECK (kind IN ('receipt', 'payment')),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'posted', 'cancelled')),
  customer_id uuid REFERENCES public.customers(id) ON DELETE SET NULL,
  payee text,
  category text NOT NULL DEFAULT 'عام',
  amount numeric NOT NULL CHECK (amount > 0),
  currency_code text NOT NULL REFERENCES public.currencies(code),
  exchange_rate_to_yer numeric NOT NULL CHECK (exchange_rate_to_yer > 0),
  payment_method text NOT NULL DEFAULT 'نقدي',
  affects_drawer boolean NOT NULL DEFAULT true,
  notes text,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  posted_at timestamptz
);

CREATE INDEX vouchers_posted_date ON public.vouchers (posted_at DESC) WHERE status = 'posted';

CREATE TABLE public.cash_transactions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_type text NOT NULL CHECK (source_type IN ('sale', 'voucher')),
  source_id uuid NOT NULL,
  currency_code text NOT NULL REFERENCES public.currencies(code),
  amount numeric NOT NULL CHECK (amount <> 0),
  rate_to_yer numeric NOT NULL CHECK (rate_to_yer > 0),
  payment_method text NOT NULL,
  affects_drawer boolean NOT NULL DEFAULT true,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_type, source_id)
);

CREATE INDEX cash_transactions_date_currency ON public.cash_transactions (created_at, currency_code) WHERE affects_drawer;

CREATE TABLE public.daily_cash_closings (
  business_date date NOT NULL,
  currency_code text NOT NULL REFERENCES public.currencies(code),
  opening_amount numeric NOT NULL CHECK (opening_amount >= 0),
  expected_amount numeric NOT NULL,
  counted_amount numeric NOT NULL CHECK (counted_amount >= 0),
  difference numeric NOT NULL,
  notes text,
  closed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  closed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (business_date, currency_code)
);

