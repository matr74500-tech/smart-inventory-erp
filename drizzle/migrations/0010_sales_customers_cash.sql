CREATE OR REPLACE FUNCTION public.employee_can(_user_id uuid, _kind text, _key text)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE cfg public.employee_permissions; manager boolean;
BEGIN
  IF _user_id IS NULL THEN RETURN false; END IF;
  IF public.has_role(_user_id, 'admin') THEN RETURN true; END IF;
  SELECT * INTO cfg FROM public.employee_permissions WHERE user_id = _user_id;
  IF FOUND THEN
    RETURN CASE _kind
      WHEN 'pages' THEN _key = ANY(cfg.pages)
      WHEN 'actions' THEN _key = ANY(cfg.actions)
      WHEN 'fields' THEN _key = ANY(cfg.fields)
      ELSE false
    END;
  END IF;
  manager := public.has_role(_user_id, 'storekeeper');
  IF _kind = 'fields' THEN RETURN true; END IF;
  IF _kind = 'pages' THEN
    RETURN _key = ANY(CASE WHEN manager
      THEN ARRAY['dashboard','inventory','purchases','prices','alerts','labels','catalog','stocktake','transfers','reorders','settings','sales','customers','cash','reports','suppliers','purchase_orders']
      ELSE ARRAY['dashboard','inventory','alerts','labels','catalog','sales','customers','cash']
    END);
  END IF;
  IF _kind = 'actions' THEN
    RETURN _key = ANY(CASE WHEN manager
      THEN ARRAY['inventory.create','inventory.edit','inventory.import','inventory.export','prices.update','purchases.post','stocktake.adjust','transfers.post','reorders.receive','settings.manage','catalog.print','labels.print','sales.draft','sales.post','sales.override_price','customers.manage','cash.manage','cash.close','reports.view','suppliers.manage','purchase_orders.manage']
      ELSE ARRAY['inventory.export','catalog.print','labels.print','sales.draft','sales.post','customers.manage','cash.manage']
    END);
  END IF;
  RETURN false;
END $$;

CREATE OR REPLACE FUNCTION public.visible_products()
RETURNS SETOF jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'غير مصرح'; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM unnest(ARRAY['inventory','sales','reports','dashboard','prices','purchases','purchase_orders','suppliers','stocktake','transfers','reorders','catalog','labels','alerts','settings']) x
    WHERE public.employee_can(auth.uid(),'pages',x)
  ) THEN RETURN; END IF;
  RETURN QUERY
    SELECT (
      SELECT jsonb_object_agg(e.key,
        CASE
          WHEN e.key IN ('id','created_at','updated_at') OR public.employee_can(auth.uid(),'fields',e.key)
          THEN CASE
            WHEN e.key='attributes'
              AND EXISTS(SELECT 1 FROM public.employee_permissions WHERE user_id=auth.uid())
              AND NOT public.has_role(auth.uid(),'admin')
            THEN coalesce(
              (SELECT jsonb_object_agg(a.key,a.value) FROM jsonb_each(e.value) a
                WHERE public.employee_can(auth.uid(),'fields','attribute:'||a.key)),
              '{}'::jsonb
            )
            ELSE e.value
          END
          ELSE 'null'::jsonb
        END
      )
      FROM jsonb_each(to_jsonb(p)) e
    )
    FROM public.products p ORDER BY p.name;
END $$;

CREATE OR REPLACE FUNCTION public.save_customer(
  _id uuid, _name text, _phone text, _secondary_phone text, _address text,
  _customer_type text, _credit_limit_yer numeric, _inactive_alert_enabled boolean
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE customer_id uuid;
BEGIN
  IF NOT public.employee_can(auth.uid(), 'pages', 'customers')
    OR NOT public.employee_can(auth.uid(), 'actions', 'customers.manage') THEN
    RAISE EXCEPTION 'غير مصرح بإدارة العملاء';
  END IF;
  IF nullif(btrim(_name), '') IS NULL OR _customer_type NOT IN ('cash','credit','wholesale')
    OR _credit_limit_yer < 0 THEN
    RAISE EXCEPTION 'بيانات العميل غير صالحة';
  END IF;
  IF _id IS NULL THEN
    INSERT INTO public.customers (name, phone, secondary_phone, address, customer_type, credit_limit_yer, inactive_alert_enabled)
    VALUES (btrim(_name), btrim(coalesce(_phone,'')), nullif(btrim(_secondary_phone),''), btrim(coalesce(_address,'')), _customer_type, _credit_limit_yer, coalesce(_inactive_alert_enabled,true))
    RETURNING id INTO customer_id;
  ELSE
    UPDATE public.customers SET name=btrim(_name), phone=btrim(coalesce(_phone,'')),
      secondary_phone=nullif(btrim(_secondary_phone),''), address=btrim(coalesce(_address,'')),
      customer_type=_customer_type, credit_limit_yer=_credit_limit_yer,
      inactive_alert_enabled=coalesce(_inactive_alert_enabled,true), updated_at=now()
    WHERE id=_id AND active RETURNING id INTO customer_id;
    IF customer_id IS NULL THEN RAISE EXCEPTION 'العميل غير موجود أو غير نشط'; END IF;
  END IF;
  RETURN customer_id;
END $$;

