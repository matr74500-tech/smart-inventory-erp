-- ============================================================================
-- المرتجعات والمردودات (Returns & Refunds)
-- يربط المرتجع بفواتير البيع الأصلية، ويحدّث المخزون (return_in / return_out)
-- والحسابات (نقديًا عبر الصندوق أو آجلًا بتخفيض رصيد العميل)، مع إنشاء
-- مردودات للموردين للأصناف المرتجعة لهم.
-- ============================================================================

-- 1) تمديد قيود الأنواع للسماح بحركات المرتجعات ومصدر حركة الصندوق
ALTER TABLE public.stock_movements DROP CONSTRAINT IF EXISTS stock_movements_kind_check;
ALTER TABLE public.stock_movements ADD CONSTRAINT stock_movements_kind_check
  CHECK (kind IN ('count','purchase','sale','transfer_in','transfer_out','restock',
    'adjustment','shelf_in','shelf_out','return_in','return_out'));

ALTER TABLE public.cash_transactions DROP CONSTRAINT IF EXISTS cash_transactions_source_type_check;
ALTER TABLE public.cash_transactions ADD CONSTRAINT cash_transactions_source_type_check
  CHECK (source_type IN ('sale','voucher','return'));

-- 2) جداول المرتجعات
CREATE TABLE IF NOT EXISTS public.sales_returns (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  operation_id uuid NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','posted','cancelled')),
  invoice_id uuid REFERENCES public.sales_invoices(id) ON DELETE SET NULL,
  customer_id uuid REFERENCES public.customers(id) ON DELETE SET NULL,
  customer_name text,
  warehouse_id uuid NOT NULL REFERENCES public.warehouses(id),
  currency_code text NOT NULL REFERENCES public.currencies(code),
  exchange_rate_to_yer numeric NOT NULL CHECK (exchange_rate_to_yer > 0),
  refund_kind text NOT NULL DEFAULT 'credit' CHECK (refund_kind IN ('cash','credit')),
  payment_method text NOT NULL DEFAULT 'نقدي',
  affects_drawer boolean NOT NULL DEFAULT false,
  subtotal_yer numeric NOT NULL DEFAULT 0 CHECK (subtotal_yer >= 0),
  total_yer numeric NOT NULL DEFAULT 0 CHECK (total_yer >= 0),
  notes text,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  posted_at timestamptz
);
CREATE INDEX IF NOT EXISTS sales_returns_posted_date ON public.sales_returns (posted_at DESC) WHERE status = 'posted';
CREATE INDEX IF NOT EXISTS sales_returns_invoice ON public.sales_returns (invoice_id);
CREATE INDEX IF NOT EXISTS sales_returns_customer ON public.sales_returns (customer_id, posted_at DESC);

CREATE TABLE IF NOT EXISTS public.sales_return_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  return_id uuid NOT NULL REFERENCES public.sales_returns(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity numeric NOT NULL CHECK (quantity > 0),
  unit_price_yer numeric NOT NULL CHECK (unit_price_yer >= 0),
  condition text NOT NULL DEFAULT 'intact' CHECK (condition IN ('intact','damaged','other')),
  disposition text NOT NULL DEFAULT 'restock' CHECK (disposition IN ('restock','scrap','supplier_return')),
  total_yer numeric NOT NULL CHECK (total_yer >= 0)
);
CREATE INDEX IF NOT EXISTS sales_return_items_return ON public.sales_return_items (return_id);
CREATE INDEX IF NOT EXISTS sales_return_items_product ON public.sales_return_items (product_id);

-- 3) مردودات الموردين (تُنشأ عندما تكون disposition = supplier_return)
CREATE TABLE IF NOT EXISTS public.supplier_returns (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  supplier_id uuid NOT NULL REFERENCES public.suppliers(id),
  warehouse_id uuid NOT NULL REFERENCES public.warehouses(id),
  status text NOT NULL DEFAULT 'posted' CHECK (status IN ('posted','cancelled')),
  total_cost numeric NOT NULL DEFAULT 0 CHECK (total_cost >= 0),
  notes text,
  return_id uuid REFERENCES public.sales_returns(id) ON DELETE SET NULL,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS supplier_returns_supplier ON public.supplier_returns (supplier_id);
CREATE INDEX IF NOT EXISTS supplier_returns_return ON public.supplier_returns (return_id);

CREATE TABLE IF NOT EXISTS public.supplier_return_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  supplier_return_id uuid NOT NULL REFERENCES public.supplier_returns(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity numeric NOT NULL CHECK (quantity > 0),
  unit_cost numeric NOT NULL CHECK (unit_cost >= 0)
);
CREATE INDEX IF NOT EXISTS supplier_return_items_sr ON public.supplier_return_items (supplier_return_id);

