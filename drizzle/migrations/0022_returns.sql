-- 5) تمديد صلاحيات employee_can بصفحة "returns" وإجراء "returns.manage"
CREATE OR REPLACE FUNCTION public.employee_can(_user_id uuid, _kind text, _key text)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE cfg public.employee_permissions; manager boolean;
BEGIN
  IF _user_id IS NULL THEN RETURN false; END IF;
  IF public.has_role(_user_id, 'admin') THEN RETURN true; END IF;
  SELECT * INTO cfg FROM public.employee_permissions WHERE user_id = _user_id;
  IF FOUND THEN
    RETURN CASE _kind
      WHEN 'pages' THEN _key = ANY(cfg.pages)
      WHEN 'actions' THEN _key = ANY(cfg.actions)
      WHEN 'fields' THEN _key = ANY(cfg.fields)
      ELSE false
    END;
  END IF;
  manager := public.has_role(_user_id, 'storekeeper');
  IF _kind = 'fields' THEN RETURN true; END IF;
  IF _kind = 'pages' THEN
    RETURN _key = ANY(CASE WHEN manager
      THEN ARRAY['dashboard','inventory','purchases','prices','alerts','labels','catalog','stocktake','transfers','reorders','settings','sales','customers','cash','reports','suppliers','purchase_orders','returns']
      ELSE ARRAY['dashboard','inventory','alerts','labels','catalog','sales','customers','cash','returns']
    END);
  END IF;
  IF _kind = 'actions' THEN
    RETURN _key = ANY(CASE WHEN manager
      THEN ARRAY['inventory.create','inventory.edit','inventory.import','inventory.export','prices.update','purchases.post','stocktake.adjust','transfers.post','reorders.receive','settings.manage','catalog.print','labels.print','sales.draft','sales.post','sales.override_price','customers.manage','cash.manage','cash.close','reports.view','suppliers.manage','purchase_orders.manage','returns.manage']
      ELSE ARRAY['inventory.export','catalog.print','labels.print','sales.draft','sales.post','customers.manage','cash.manage','returns.manage']
    END);
  END IF;
  RETURN false;
END $$;

-- 6) اعتماد مرتجع (إنشاء + ترحيل ذرّي) — يحدّث المخزون والحسابات
--    process: _items = [{ product_id, quantity, unit_price_yer, condition, disposition }]
CREATE OR REPLACE FUNCTION public.post_return(
  _operation_id uuid,
  _invoice_id uuid,
  _customer_id uuid,
  _customer_name text,
  _warehouse uuid,
  _currency_code text,
  _rate_to_yer numeric,
  _refund_kind text,
  _payment_method text,
  _notes text,
  _items jsonb
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  line jsonb;
  v_total numeric := 0;
  v_affects boolean;
  sr_id uuid;
  sup record;
  v_return_id uuid;
  v_product uuid;
  v_qty numeric;
  v_price numeric;
  v_condition text;
  v_disposition text;
  v_sold numeric;
  v_returned numeric;
BEGIN
  -- الوجاهة: منع التكرار (idempotent)
  SELECT id INTO v_return_id FROM public.sales_returns WHERE operation_id = _operation_id;
  IF v_return_id IS NOT NULL THEN RETURN v_return_id; END IF;

  IF NOT public.employee_can(auth.uid(),'pages','returns')
    OR NOT public.employee_can(auth.uid(),'actions','returns.manage')
    OR NOT public.employee_can(auth.uid(),'fields','quantity') THEN
    RAISE EXCEPTION 'غير مصرح باعتماد المرتجعات';
  END IF;
  IF _warehouse IS NULL OR _rate_to_yer IS NULL OR _rate_to_yer <= 0
    OR _refund_kind NOT IN ('cash','credit')
    OR jsonb_typeof(_items) <> 'array' OR jsonb_array_length(_items) = 0 THEN
    RAISE EXCEPTION 'بيانات المرتجع غير صالحة';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.warehouses WHERE id=_warehouse) THEN
    RAISE EXCEPTION 'المستودع غير موجود';
  END IF;
  IF _customer_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.customers WHERE id=_customer_id AND active) THEN
    RAISE EXCEPTION 'العميل غير موجود أو غير نشط';
  END IF;
  IF _refund_kind = 'credit' AND _customer_id IS NULL THEN
    RAISE EXCEPTION 'اختر عميلاً لرد القيمة إلى الحساب';
  END IF;

  v_affects := (_refund_kind = 'cash');
  IF v_affects AND EXISTS (
    SELECT 1 FROM public.daily_cash_closings
    WHERE business_date = current_date AND currency_code = _currency_code
  ) THEN
    RAISE EXCEPTION 'تم إقفال الصندوق لهذه العملة اليوم';
  END IF;

  INSERT INTO public.sales_returns (status, operation_id, invoice_id, customer_id, customer_name,
    warehouse_id, currency_code, exchange_rate_to_yer, refund_kind, payment_method, affects_drawer, notes, created_by)
  VALUES ('draft', _operation_id, _invoice_id, _customer_id, nullif(btrim(_customer_name),''), _warehouse,
    _currency_code, _rate_to_yer, _refund_kind, coalesce(nullif(btrim(_payment_method),''),'نقدي'),
    v_affects, nullif(btrim(_notes),''), auth.uid())
  RETURNING id INTO v_return_id;

  -- معالجة الأصناف
  FOR line IN SELECT value FROM jsonb_array_elements(_items) LOOP
    v_product := (line->>'product_id')::uuid;
    v_qty := (line->>'quantity')::numeric;
    v_price := (line->>'unit_price_yer')::numeric;
    v_condition := coalesce(line->>'condition','intact');
    v_disposition := coalesce(line->>'disposition','restock');

    IF v_qty IS NULL OR v_qty <= 0 OR v_price IS NULL OR v_price < 0
      OR v_condition NOT IN ('intact','damaged','other')
      OR v_disposition NOT IN ('restock','scrap','supplier_return') THEN
      RAISE EXCEPTION 'بيانات صنف غير صالحة في المرتجع';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.products WHERE id=v_product) THEN
      RAISE EXCEPTION 'الصنف غير موجود';
    END IF;
    -- منع تجاوز الكمية المباعة (عند وجود فاتورة أصلية)
    IF _invoice_id IS NOT NULL THEN
      SELECT coalesce(sum(quantity),0) INTO v_sold FROM public.sales_items
        WHERE invoice_id=_invoice_id AND product_id=v_product;
      SELECT coalesce(sum(ri.quantity),0) INTO v_returned
        FROM public.sales_return_items ri
        JOIN public.sales_returns r2 ON r2.id=ri.return_id
        WHERE r2.invoice_id=_invoice_id AND r2.status='posted' AND ri.product_id=v_product;
      IF v_returned + v_qty > v_sold THEN
        RAISE EXCEPTION 'كمية المرتجع للصنف % تتجاوز الكمية المباعة', v_product;
      END IF;
    END IF;

    INSERT INTO public.sales_return_items (return_id, product_id, quantity, unit_price_yer,
      condition, disposition, total_yer)
      VALUES (v_return_id, v_product, v_qty, v_price, v_condition, v_disposition, v_qty*v_price);
    v_total := v_total + v_qty*v_price;

    -- زيادة المخزون (استلام البضاعة المرتجعة)
    INSERT INTO public.stock (product_id, warehouse_id, quantity, updated_at)
      VALUES (v_product, _warehouse, v_qty, now())
      ON CONFLICT (product_id, warehouse_id) DO UPDATE
        SET quantity = public.stock.quantity + excluded.quantity, updated_at = now();
    INSERT INTO public.stock_movements (product_id, warehouse_id, kind, quantity, user_id, note)
      VALUES (v_product, _warehouse, 'return_in', v_qty, auth.uid(), 'مرتجع');

    -- التصرف بالمصير
    IF v_disposition = 'scrap' THEN
      UPDATE public.stock SET quantity = quantity - v_qty, updated_at = now()
        WHERE product_id=v_product AND warehouse_id=_warehouse;
      INSERT INTO public.stock_movements (product_id, warehouse_id, kind, quantity, user_id, note)
        VALUES (v_product, _warehouse, 'return_out', -v_qty, auth.uid(), 'إتلاف مرتجع');
    ELSIF v_disposition = 'supplier_return' THEN
      UPDATE public.stock SET quantity = quantity - v_qty, updated_at = now()
        WHERE product_id=v_product AND warehouse_id=_warehouse;
      INSERT INTO public.stock_movements (product_id, warehouse_id, kind, quantity, user_id, note)
        VALUES (v_product, _warehouse, 'return_out', -v_qty, auth.uid(), 'إرجاع للمورد');
    END IF;
  END LOOP;

  UPDATE public.sales_returns SET status='posted', posted_at=now(), subtotal_yer=v_total, total_yer=v_total
    WHERE id=v_return_id;

  -- مردودات الموردين: مجموعة لكل مورد رئيسي للأصناف ذات disposition = supplier_return
  FOR sup IN
    SELECT DISTINCT ps.supplier_id
    FROM public.sales_return_items ri
    JOIN public.product_suppliers ps ON ps.product_id = ri.product_id AND ps.is_primary
    JOIN public.suppliers s ON s.id = ps.supplier_id AND s.active
    WHERE ri.return_id = v_return_id AND ri.disposition = 'supplier_return'
  LOOP
    INSERT INTO public.supplier_returns (supplier_id, warehouse_id, status, notes, return_id, created_by)
      VALUES (sup.supplier_id, _warehouse, 'posted', 'مرتجع من العميل', v_return_id, auth.uid())
      RETURNING id INTO sr_id;
    INSERT INTO public.supplier_return_items (supplier_return_id, product_id, quantity, unit_cost)
      SELECT sr_id, ri.product_id, ri.quantity, coalesce(p.cost,0)
      FROM public.sales_return_items ri
      JOIN public.products p ON p.id = ri.product_id
      JOIN public.product_suppliers ps ON ps.product_id = ri.product_id AND ps.is_primary
      WHERE ri.return_id = v_return_id AND ri.disposition = 'supplier_return'
        AND ps.supplier_id = sup.supplier_id;
    UPDATE public.supplier_returns SET total_cost =
      (SELECT coalesce(sum(quantity*unit_cost),0) FROM public.supplier_return_items WHERE supplier_return_id = sr_id)
      WHERE id = sr_id;
  END LOOP;

  -- أثر الحسابات
  IF _refund_kind = 'credit' THEN
    UPDATE public.customers SET balance_yer = balance_yer - v_total, updated_at = now()
      WHERE id = _customer_id;
  ELSE
    INSERT INTO public.cash_transactions (source_type, source_id, currency_code, amount, rate_to_yer,
      payment_method, affects_drawer, created_by)
      VALUES ('return', v_return_id, _currency_code, -(v_total / _rate_to_yer), _rate_to_yer,
        coalesce(nullif(btrim(_payment_method),''),'نقدي'), true, auth.uid());
  END IF;

  RETURN v_return_id;
END $$;

-- 7) غلاف غير متزامن (idempotent) لدعم العمل دون اتصال
CREATE OR REPLACE FUNCTION public.post_return_offline(
  _operation_id uuid,
  _invoice_id uuid,
  _customer_id uuid,
  _customer_name text,
  _warehouse uuid,
  _currency_code text,
  _rate_to_yer numeric,
  _refund_kind text,
  _payment_method text,
  _notes text,
  _items jsonb
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.offline_operation_receipts WHERE operation_id = _operation_id) THEN
    RETURN (SELECT id FROM public.sales_returns WHERE operation_id = _operation_id);
  END IF;
  INSERT INTO public.offline_operation_receipts (operation_id, operation_kind, user_id)
    VALUES (_operation_id, 'post_return', auth.uid());
  RETURN public.post_return(_operation_id, _invoice_id, _customer_id, _customer_name, _warehouse,
    _currency_code, _rate_to_yer, _refund_kind, _payment_method, _notes, _items);
END $$;

-- 8) الصلاحيات
REVOKE ALL ON FUNCTION public.post_return(uuid,uuid,uuid,uuid,text,numeric,text,text,text,jsonb) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.post_return_offline(uuid,uuid,uuid,uuid,text,numeric,text,text,text,jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.post_return(uuid,uuid,uuid,uuid,text,numeric,text,text,text,jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.post_return_offline(uuid,uuid,uuid,uuid,text,numeric,text,text,text,jsonb) TO authenticated;